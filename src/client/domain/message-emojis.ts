export type MessageTextPart = { text: string; label?: string };

/** 只识别完整方括号标记，不解析 HTML，也不改变普通文字和原生 Emoji。 */
export function messageEmojiParts(text: string): MessageTextPart[] {
  return text
    .split(/(\[[^\[\]\r\n]{1,24}\])/g)
    .filter(Boolean)
    .map((part) => {
      const label = part.slice(1, -1);
      if (part.startsWith('[') && part.endsWith(']') && Object.hasOwn(messageEmojis, label))
        return { text: messageEmojis[label], label };
      return { text: part };
    });
}
